const requireCatalogFood = (catalogFoods, barcode) => {
	const food = catalogFoods.get(barcode);
	if (!food) {
		throw new Error(`Local QA food ${barcode} is unavailable.`);
	}
	return food;
};

const seedTestFoodLists = async (userClient, account, catalogFoods) => {
	for (const listType of ["fridge", "shopping"]) {
		const foods = account.lists[listType].map((barcode) =>
			requireCatalogFood(catalogFoods, barcode),
		);
		if (foods.length === 0) continue;
		const result = requireSuccessfulResult(
			await userClient.rpc("place_user_food_list_items", {
				p_foods: foods,
				p_list_type: listType,
			}),
			`Seed ${listType} ingredients for ${account.email}`,
		);
		if (result !== "added" && result !== "duplicate") {
			throw new Error(
				`Unexpected ${listType} fixture result for ${account.email}: ${result}.`,
			);
		}
	}
};

const createSavedDrink = (definition, catalogFoods, id = randomUUID()) => {
	const foods = definition.ingredients.map(([barcode]) =>
		requireCatalogFood(catalogFoods, barcode),
	);
	const servingGrams = Object.fromEntries(
		definition.ingredients.map(([barcode, grams]) => [
			requireCatalogFood(catalogFoods, barcode).fdcId,
			grams,
		]),
	);
	const servingQuantities = { ...servingGrams };
	const servingUnits = Object.fromEntries(
		foods.map((food) => [food.fdcId, "g"]),
	);

	return {
		id,
		name: definition.name,
		createdAt: new Date(definition.createdAt).getTime(),
		foods,
		selected: qaNutrientOptions.map(({ id: nutrientId }) => nutrientId),
		options: qaNutrientOptions,
		nutrientGoals: definition.goals,
		servingGrams,
		servingQuantities,
		servingUnits,
	};
};

const seedTestSavedDrinks = async (userClient, account, catalogFoods) => {
	if (account.savedDrinkKeys.length === 0) return;
	const existingRows = requireSuccessfulResult(
		await userClient.from("saved_drinks").select("id, name"),
		`Load saved mixes for ${account.email}`,
	);
	const existingIdsByName = new Map(
		existingRows.map((row) => [row.name.toLowerCase(), row.id]),
	);

	for (const savedDrinkKey of account.savedDrinkKeys) {
		const definition = localQaSavedDrinks[savedDrinkKey];
		const drink = createSavedDrink(
			definition,
			catalogFoods,
			existingIdsByName.get(definition.name.toLowerCase()) ?? randomUUID(),
		);
		const result = requireSuccessfulResult(
			await userClient.rpc("save_saved_drink", {
				p_created_at: new Date(drink.createdAt).toISOString(),
				p_drink: drink,
				p_id: drink.id,
				p_name: drink.name,
			}),
			`Seed saved mix ${drink.name} for ${account.email}`,
		);
		if (result !== "saved" && result !== "duplicate") {
			throw new Error(
				`Unexpected saved mix result for ${account.email}: ${result}.`,
			);
		}
	}
};

const seedTestMixPreferences = async (userClient, account, catalogFoods) => {
	if (!account.activeMixKey) return;
	const definition = localQaSavedDrinks[account.activeMixKey];
	const drink = createSavedDrink(definition, catalogFoods);
	const result = requireSuccessfulResult(
		await userClient.rpc("save_mix_preferences", {
			p_nutrient_goals: drink.nutrientGoals,
			p_mix_state: {
				version: 1,
				selected: drink.selected,
				options: drink.options,
				selectedFoodIds: drink.foods.map((food) => food.fdcId),
				servingGrams: drink.servingGrams,
				servingQuantities: drink.servingQuantities,
				servingUnits: drink.servingUnits,
			},
		}),
		`Seed Mix state for ${account.email}`,
	);
	if (result !== true) {
		throw new Error(`Mix state could not be seeded for ${account.email}.`);
	}
};

