const collectDatabaseTestFiles = async (directory) => {
	const entries = await readdir(directory, { withFileTypes: true });
	const files = [];
	for (const entry of entries) {
		const entryUrl = new URL(entry.name, directory);
		if (entry.isDirectory()) {
			entryUrl.pathname += "/";
			files.push(...await collectDatabaseTestFiles(entryUrl));
		} else if (entry.isFile() && entry.name.endsWith(".sql")) {
			files.push(entryUrl);
		}
	}
	return files.sort((left, right) => left.pathname.localeCompare(right.pathname));
};

const runDatabaseTests = async () => {
	const databaseContainer = await getLocalServiceContainer("db");
	const testFiles = await collectDatabaseTestFiles(databaseTestDirectory);
	if (testFiles.length === 0) {
		throw new Error("No pgTAP database tests were found.");
	}

	runCommand(
		"docker",
		[
			"exec",
			databaseContainer,
			"psql",
			"--set",
			"ON_ERROR_STOP=1",
			"--username",
			"postgres",
			"--dbname",
			"postgres",
			"--command",
			"create extension if not exists pgtap with schema extensions",
		],
		{ capture: true },
	);

	for (const testFile of testFiles) {
		const testSql = await readFile(testFile, "utf8");
		const output = runCommand(
			"docker",
			[
				"exec",
				"--env",
				"PGOPTIONS=--search_path=public,extensions",
				"--interactive",
				databaseContainer,
				"psql",
				"--set",
				"ON_ERROR_STOP=1",
				"--username",
				"postgres",
				"--dbname",
				"postgres",
				"--tuples-only",
				"--no-align",
			],
			{ capture: true, input: testSql },
		);
		if (!/^1\.\.\d+$/m.test(output) || /^not ok\b/m.test(output)) {
			throw new Error(
				`Database test ${fileURLToPath(testFile)} failed:\n${output.trim()}`,
			);
		}
		console.log(output.trim());
	}
};

const requireSuccessfulResult = (result, label) => {
	if (result.error) throw new Error(`${label}: ${result.error.message}`);
	return result.data;
};

const loadTestCatalogFoods = async (admin) => {
	const expectedBarcodes = getLocalQaCatalogBarcodes();
	const products = requireSuccessfulResult(
		await admin
			.from("shared_products")
			.select("id, barcode, confidence, food")
			.in("barcode", expectedBarcodes)
			.eq("status", "active"),
		"Load local QA catalog products for account personas",
	);
	const productsByBarcode = new Map(
		products.map((product) => {
			const food = {
				...product.food,
				customFood: false,
				sharedProductId: product.id,
				sharedProductConfidence: product.confidence,
			};
			if (!Number.isSafeInteger(Number(food.fdcId))) {
				throw new Error(
					`Local QA catalog product ${product.barcode} has no valid food identity.`,
				);
			}
			return [product.barcode, food];
		}),
	);

	for (const barcode of expectedBarcodes) {
		if (!productsByBarcode.has(barcode)) {
			throw new Error(
				`Local QA catalog product ${barcode} is unavailable for persona seeding.`,
			);
		}
	}

	return productsByBarcode;
};

const wait = (milliseconds) =>
	new Promise((resolve) => {
		setTimeout(resolve, milliseconds);
	});

const formatSupabaseError = (error) => {
	if (!error) return "Unknown service error.";
	if (typeof error.message === "string" && error.message.trim()) {
		return error.message;
	}
	try {
		return JSON.stringify(error);
	} catch {
		return String(error);
	}
};

const waitForLocalServices = async (admin) => {
	let lastAuthError;
	let lastDatabaseError;

	for (let attempt = 1; attempt <= serviceReadinessAttempts; attempt += 1) {
		const [usersResult, profilesResult] = await Promise.all([
			admin.auth.admin.listUsers({ page: 1, perPage: 1000 }),
			admin.from("profiles").select("user_id").limit(1),
		]);

		if (!usersResult.error && !profilesResult.error) {
			return usersResult.data;
		}

		lastAuthError = usersResult.error;
		lastDatabaseError = profilesResult.error;
		if (attempt < serviceReadinessAttempts) {
			await wait(serviceReadinessDelayMs);
		}
	}

	throw new Error(
		[
			"Local Supabase services did not become ready before QA account seeding.",
			`Auth: ${formatSupabaseError(lastAuthError)}`,
			`Database: ${formatSupabaseError(lastDatabaseError)}`,
		].join(" "),
	);
};

